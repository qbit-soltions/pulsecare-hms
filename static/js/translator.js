  // Language Switch Action
  window.changePulseCareLanguage = function (langCode, e) {
    if (e && e.preventDefault) e.preventDefault();
    setLanguageCookies(langCode);

    if (window.PulseCareVoice && window.PulseCareVoice.onLanguageChanged) {
      window.PulseCareVoice.onLanguageChanged(langCode);
    }
    
    // Switch Google Translate combo if present
    const select = document.querySelector(".goog-te-combo");
    if (select) {
      select.value = langCode;
      select.dispatchEvent(new Event("change"));
    }

    // Call server to persist session and reload
    fetch("/set-language/" + langCode, {
      headers: { "X-Requested-With": "XMLHttpRequest" }
    })
      .then(function() {
        window.location.reload();
      })
      .catch(function() {
        window.location.href = "/set-language/" + langCode;
      });
  };

  document.addEventListener("DOMContentLoaded", function () {
    const currentLang = getActiveLanguage();

    // Attach click listeners to language dropdown items
    document.querySelectorAll(".lang-select-item").forEach(function (item) {
      item.addEventListener("click", function (e) {
        const targetLang = this.getAttribute("data-lang");
        if (targetLang) {
          changePulseCareLanguage(targetLang, e);
        }
      });
    });

    // Run client-side DOM translation fallback immediately
    if (currentLang !== "en") {
      translatePageDOM(currentLang);
    }

    // Check periodically if google translate combo is available to ensure sync
    let tries = 0;
    const interval = setInterval(function () {
      tries++;
      const select = document.querySelector(".goog-te-combo");
      if (select) {
        clearInterval(interval);
        if (currentLang !== "en" && select.value !== currentLang) {
          select.value = currentLang;
          select.dispatchEvent(new Event("change"));
        }
      }
      if (tries > 30) clearInterval(interval);
    }, 200);
  });
