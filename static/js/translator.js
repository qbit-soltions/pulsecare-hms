  function getActiveLanguage() {
    const pMatch = document.cookie.match(/(?:^|;\s*)pulse_lang=([^;]+)/);
    if (pMatch && pMatch[1]) return pMatch[1];

    const gMatch = document.cookie.match(/(?:^|;\s*)googtrans=\/en\/([^;]+)/);
    if (gMatch && gMatch[1]) return gMatch[1];

    const stored = localStorage.getItem("pulsecare_lang");
    if (stored) return stored;

    const htmlLang = document.documentElement.getAttribute("lang");
    if (htmlLang && htmlLang !== "en") return htmlLang;

    return "en";
  }

  function setLanguageCookies(lang) {
    const hostname = window.location.hostname;
    localStorage.setItem("pulsecare_lang", lang);
    const targetTrans = lang === "en" ? "/en/en" : "/en/" + lang;

    // Set standard path cookies
    document.cookie = "googtrans=" + targetTrans + "; path=/; max-age=2592000";
    document.cookie = "pulse_lang=" + lang + "; path=/; max-age=2592000";

    // Set domain cookies if domain contains dots (e.g. onrender.com)
    if (hostname && hostname.indexOf(".") !== -1) {
      document.cookie = "googtrans=" + targetTrans + "; path=/; domain=" + hostname + "; max-age=2592000";
      document.cookie = "pulse_lang=" + lang + "; path=/; domain=" + hostname + "; max-age=2592000";
      
      const domainParts = hostname.split(".");
      if (domainParts.length >= 2) {
        const rootDomain = "." + domainParts.slice(-2).join(".");
        document.cookie = "googtrans=" + targetTrans + "; path=/; domain=" + rootDomain + "; max-age=2592000";
        document.cookie = "pulse_lang=" + lang + "; path=/; domain=" + rootDomain + "; max-age=2592000";
      }
    }
  }

  function translatePageDOM(lang) {
    if (!lang || lang === "en" || !UI_DICTIONARY[lang]) return;
    const dict = UI_DICTIONARY[lang];

    const elements = document.querySelectorAll(
      "h1, h2, h3, h4, h5, h6, p, span, a, button, label, th, td, div.brand-title, div.brand-subtitle, .badge, .dropdown-item, .nav-link, .card-title, .form-label, strong, b, small"
    );

    elements.forEach(function (el) {
      if (el.closest("#google_translate_element") || el.closest(".goog-te-combo") || el.closest(".no-translate")) return;

      const text = el.innerText ? el.innerText.trim() : "";
      if (text && dict[text] && el.children.length === 0) {
        el.innerText = dict[text];
      }

      if (el.placeholder && dict[el.placeholder]) {
        el.placeholder = dict[el.placeholder];
      }
    });

    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: function(node) {
          if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;
          if (parent.tagName === "SCRIPT" || parent.tagName === "STYLE" || parent.tagName === "NOSCRIPT") return NodeFilter.FILTER_REJECT;
          if (parent.closest("#google_translate_element") || parent.closest(".goog-te-combo") || parent.closest(".no-translate")) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        }
      },
      false
    );

    let currentNode;
    while ((currentNode = walker.nextNode())) {
      const val = currentNode.nodeValue;
      const trimmed = val.trim();
      if (dict[trimmed]) {
        currentNode.nodeValue = val.replace(trimmed, dict[trimmed]);
      }
    }
  }

  // Language Switch Action
  window.changePulseCareLanguage = function (langCode, e) {
    if (e && e.preventDefault) e.preventDefault();
    setLanguageCookies(langCode);
    
    // Switch Google Translate combo if present
    const select = document.querySelector(".goog-te-combo");
    if (select) {
      select.value = langCode;
      select.dispatchEvent(new Event("change"));
    }

    // Call server to persist session and reload
    fetch("/set-language/" + langCode, {
      headers: { "X-Requested-With": "XMLHttpRequest" }
    })
      .then(function() {
        window.location.reload();
      })
      .catch(function() {
        window.location.href = "/set-language/" + langCode;
      });
  };

  document.addEventListener("DOMContentLoaded", function () {
    const currentLang = getActiveLanguage();

    // Attach click listeners to language dropdown items
    document.querySelectorAll(".lang-select-item").forEach(function (item) {
      item.addEventListener("click", function (e) {
        const targetLang = this.getAttribute("data-lang");
        if (targetLang) {
          changePulseCareLanguage(targetLang, e);
        }
      });
    });

    // Run client-side DOM translation fallback immediately
    if (currentLang !== "en") {
      translatePageDOM(currentLang);
    }

    // Check periodically if google translate combo is available to ensure sync
    let tries = 0;
    const interval = setInterval(function () {
      tries++;
      const select = document.querySelector(".goog-te-combo");
      if (select) {
        clearInterval(interval);
        if (currentLang !== "en" && select.value !== currentLang) {
          select.value = currentLang;
          select.dispatchEvent(new Event("change"));
        }
      }
      if (tries > 30) clearInterval(interval);
    }, 200);
  });
